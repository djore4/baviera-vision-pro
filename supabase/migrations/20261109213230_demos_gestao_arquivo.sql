-- Demos: gestão da frota como na "Gestão VD" da Sales Force — adicionar viaturas, arquivar como
-- vendidas e consultar/recuperar o arquivo.
--
--  * viaturas_vendidas: o arquivo da Sales Force (já existe em produção; aqui só se garante a tabela
--    em ambientes novos). A política "auth_rw_viaturas_vendidas" deixava QUALQUER conta autenticada
--    ler e escrever o arquivo, com custos e margens (`inputs`/`stats`); passa a valer a mesma regra
--    das restantes tabelas partilhadas (salesforce_users: quem consta de `utilizadores`).
--    Esta plataforma acede só pelas funções abaixo.
--  * demos_calc_stats / demos_validar_inputs: fórmulas e validação de preços partilhadas (as de
--    demos_gravar_precos, agora reutilizadas).
--  * demos_criar_viatura: administrador, ou 'demos:inserir-viaturas' (edit) nos SEUS locais.
--  * demos_arquivar_viatura / demos_vendidas / demos_repor_viatura: administrador, ou
--    'demos:precos' (edit) nas viaturas do SEU local. Arquivar cristaliza preço e estatísticas, move a
--    viatura para viaturas_vendidas e regista em `historico`; repor faz o inverso.
-- Depende de 20261109211555 (demos_gravar_precos) e 20261109211511 (demos_por_local).

create table if not exists public.viaturas_vendidas (
  id bigint generated by default as identity primary key,
  chassis text, matricula text, modelo text, versao text, encomenda text, estado_entrega text,
  estado_negocio text, data_matricula text, tipologia jsonb, local jsonb, marca jsonb, kms text,
  observacoes text, link_fotos text, inputs jsonb, stats jsonb, preco_final numeric,
  data_venda timestamptz default now(), vendido_por text, created_at timestamptz default now(),
  iva_dedutivel boolean not null default false
);
alter table public.viaturas_vendidas enable row level security;
drop policy if exists auth_rw_viaturas_vendidas on public.viaturas_vendidas;
drop policy if exists salesforce_users on public.viaturas_vendidas;
create policy salesforce_users on public.viaturas_vendidas
  for all to authenticated
  using ((select public.is_salesforce_user())) with check ((select public.is_salesforce_user()));

-- ── Validação e estatísticas ────────────────────────────────────────────────
create or replace function public.demos_validar_inputs(p_inputs jsonb)
returns void
language plpgsql
immutable
set search_path = ''
as $$
declare
  k text;
  n jsonb;
  allowed constant text[] := array[
    'pvb', 'opc', 'bsi', 'eco', 'leg', 'isv',
    'mgb', 'esf', 'pac', 'dem', 'sup', 'depreciacoes', 'pvp_desc'];
begin
  if jsonb_typeof(p_inputs) is distinct from 'object' then
    raise exception 'Preços inválidos.' using errcode = '22023';
  end if;
  for k, n in select * from jsonb_each(p_inputs) loop
    if not (k = any (allowed)) then
      raise exception 'Campo de preço desconhecido: %.', k using errcode = '22023';
    end if;
    if jsonb_typeof(n) is distinct from 'number' then
      raise exception 'O campo % tem de ser numérico.', k using errcode = '22023';
    end if;
    if abs((n #>> '{}')::numeric) > 10000000 then
      raise exception 'Valor fora do intervalo em %.', k using errcode = '22023';
    end if;
    if k in ('mgb', 'esf', 'pac', 'dem', 'sup') and ((n #>> '{}')::numeric < 0 or (n #>> '{}')::numeric > 1) then
      raise exception 'A percentagem % tem de estar entre 0 e 100.', k using errcode = '22023';
    end if;
  end loop;
end;
$$;

-- `stats` com as fórmulas da Sales Force (Preço Mín. inclui o BSI); preserva as chaves que já tinha (idade…).
create or replace function public.demos_calc_stats(p_inputs jsonb, p_stats jsonb)
returns jsonb
language sql
immutable
set search_path = ''
as $$
  with v as (
    select coalesce((p_inputs ->> 'pvb')::numeric, 0) pvb, coalesce((p_inputs ->> 'opc')::numeric, 0) opc,
           coalesce((p_inputs ->> 'bsi')::numeric, 0) bsi, coalesce((p_inputs ->> 'eco')::numeric, 0) eco,
           coalesce((p_inputs ->> 'leg')::numeric, 0) leg, coalesce((p_inputs ->> 'isv')::numeric, 0) isv,
           coalesce((p_inputs ->> 'pvp_desc')::numeric, 0) pdesc, coalesce((p_inputs ->> 'depreciacoes')::numeric, 0) dep,
           coalesce((p_inputs ->> 'mgb')::numeric, 0) + coalesce((p_inputs ->> 'esf')::numeric, 0)
             + coalesce((p_inputs ->> 'pac')::numeric, 0) + coalesce((p_inputs ->> 'dem')::numeric, 0)
             + coalesce((p_inputs ->> 'sup')::numeric, 0) dperc
  ), c as (
    select v.*, (pvb + opc) * dperc deur, (pvb + opc + bsi + eco + leg + isv) * 1.23 pvp_bruto from v
  ), d as (
    select c.*, pvp_bruto - deur * 1.23 pmin from c
  )
  select (case jsonb_typeof(p_stats) when 'object' then p_stats else '{}'::jsonb end)
    || jsonb_build_object(
         'pvp_bruto', pvp_bruto, 'pvp_final', pdesc, 'mg', pdesc - pmin + dep,
         'penetracao', case when pvb > 0 then opc / pvb else 0 end,
         'desc_perc', dperc, 'desc_eur', deur,
         'iva', pvp_bruto / 1.23 * 0.23, 'preco_minimo', pmin,
         'mg_perc', case when pvb + opc > 0 then (pdesc - pmin + dep) / (pvb + opc) else 0 end,
         's_iva', pdesc / 1.23)
  from d;
$$;

-- demos_gravar_precos passa a usar as funções partilhadas (comportamento igual).
create or replace function public.demos_gravar_precos(p_chassis text, p_inputs jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.viaturas;
  base jsonb;
  i jsonb;
begin
  select * into v from public.viaturas where chassis = p_chassis;
  if not found then
    raise exception 'Viatura não encontrada.' using errcode = 'P0002';
  end if;
  if not ((select public.is_app_admin())
          or ((select public.has_access('demos:precos', 'edit')) and public.viaturas_local_ok(v.local))) then
    raise exception 'Sem permissão para gerir os preços desta viatura.' using errcode = '42501';
  end if;
  perform public.demos_validar_inputs(p_inputs);
  base := case jsonb_typeof(v.inputs)
            when 'object' then v.inputs
            when 'string' then (v.inputs #>> '{}')::jsonb
            else '{}'::jsonb end;
  i := base || p_inputs;
  update public.viaturas set inputs = i, stats = public.demos_calc_stats(i, v.stats) where chassis = p_chassis;
  insert into public.historico (tabela, acao, registo_id, detalhes)
    values ('viaturas', 'ATUALIZAR_PRECOS', p_chassis,
            jsonb_build_object('editado_por', auth.jwt() ->> 'email', 'origem', 'baviera-vision-pro',
                               'alterados', (select jsonb_agg(key) from jsonb_object_keys(p_inputs) key)));
  return i;
end;
$$;

-- ── Adicionar viatura ───────────────────────────────────────────────────────
-- p: chassis, matricula, encomenda, modelo, versao (obrigatórios); estado_negocio (VD|VU), marca
-- ('BMW'|'BMW Motorrad'), tipologia[], local[] (obrigatório), data_matricula, kms, estado_entrega,
-- link_fotos, iva_dedutivel, inputs{}. Não substitui nada: chassis ou matrícula repetidos são recusados.
create or replace function public.demos_criar_viatura(p jsonb)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  ch text := upper(btrim(coalesce(p ->> 'chassis', '')));
  mat text := upper(regexp_replace(coalesce(p ->> 'matricula', ''), '[^A-Za-z0-9]', '', 'g'));
  enc text := btrim(coalesce(p ->> 'encomenda', ''));
  v_modelo text := btrim(coalesce(p ->> 'modelo', ''));
  v_versao text := btrim(coalesce(p ->> 'versao', ''));
  negocio text := coalesce(nullif(p ->> 'estado_negocio', ''), 'VD');
  v_marca text := coalesce(nullif(p ->> 'marca', ''), 'BMW');
  loc jsonb := p -> 'local';
  tip jsonb := coalesce(p -> 'tipologia', '[]'::jsonb);
  dmat date;
  kms int;
  ins jsonb := coalesce(p -> 'inputs', '{}'::jsonb);
  v_inputs jsonb;
  row_ public.viaturas;
begin
  if jsonb_typeof(loc) is distinct from 'array' or jsonb_array_length(loc) = 0 then
    raise exception 'Indica a localização da viatura.' using errcode = '22023';
  end if;
  if not ((select public.is_app_admin())
          or ((select public.has_access('demos:inserir-viaturas', 'edit')) and public.viaturas_local_ok(loc))) then
    raise exception 'Sem permissão para adicionar viaturas neste local.' using errcode = '42501';
  end if;
  if ch = '' or length(ch) > 40 then raise exception 'Chassis em falta ou inválido.' using errcode = '22023'; end if;
  if length(mat) <> 6 then raise exception 'Matrícula inválida (formato AA-00-BB).' using errcode = '22023'; end if;
  mat := substr(mat, 1, 2) || '-' || substr(mat, 3, 2) || '-' || substr(mat, 5, 2);
  if enc = '' then raise exception 'Encomenda em falta.' using errcode = '22023'; end if;
  if v_modelo = '' or v_versao = '' then raise exception 'Modelo e versão são obrigatórios.' using errcode = '22023'; end if;
  if negocio not in ('VD', 'VU') then raise exception 'Tipo de viatura inválido.' using errcode = '22023'; end if;
  if v_marca not in ('BMW', 'BMW Motorrad') then raise exception 'Marca inválida.' using errcode = '22023'; end if;
  if jsonb_typeof(tip) is distinct from 'array' then raise exception 'Tecnologia inválida.' using errcode = '22023'; end if;
  if exists (select 1 from jsonb_array_elements(loc) l where jsonb_typeof(l) <> 'string')
     or exists (select 1 from jsonb_array_elements(tip) t where jsonb_typeof(t) <> 'string') then
    raise exception 'Listas inválidas.' using errcode = '22023';
  end if;
  begin dmat := nullif(p ->> 'data_matricula', '')::date; exception when others then
    raise exception 'Data de matrícula inválida.' using errcode = '22023'; end;
  begin kms := nullif(p ->> 'kms', '')::int; exception when others then
    raise exception 'Quilómetros inválidos.' using errcode = '22023'; end;
  if kms < 0 then raise exception 'Quilómetros inválidos.' using errcode = '22023'; end if;
  perform public.demos_validar_inputs(ins);
  if exists (select 1 from public.viaturas where upper(chassis) = ch) then
    raise exception 'Já existe uma viatura com o chassis %.', ch using errcode = '23505';
  end if;
  if exists (select 1 from public.viaturas where upper(regexp_replace(coalesce(matricula, ''), '[^A-Za-z0-9]', '', 'g')) = replace(mat, '-', '')) then
    raise exception 'A matrícula % já está associada a outra viatura.', mat using errcode = '23505';
  end if;

  v_inputs := '{"pvb":0,"opc":0,"bsi":0,"eco":4.2,"leg":1550,"isv":0,"mgb":0,"esf":0,"pac":0,"dem":0,"sup":0,"pvp_desc":0,"depreciacoes":0}'::jsonb || ins;
  insert into public.viaturas (chassis, matricula, modelo, versao, encomenda, estado_entrega, data_matricula, kms,
                               tipologia, local, marca, estado_negocio, link_fotos, iva_dedutivel, inputs, stats)
    values (ch, mat, v_modelo, v_versao, enc, nullif(btrim(coalesce(p ->> 'estado_entrega', '')), ''), dmat, kms,
            tip, loc, jsonb_build_array(v_marca)::text, negocio, nullif(btrim(coalesce(p ->> 'link_fotos', '')), ''),
            coalesce((p ->> 'iva_dedutivel')::boolean, false), v_inputs, public.demos_calc_stats(v_inputs, '{}'::jsonb))
    returning * into row_;
  insert into public.historico (tabela, acao, registo_id, detalhes)
    values ('viaturas', 'CRIAR', ch, jsonb_build_object('editado_por', auth.jwt() ->> 'email', 'origem', 'baviera-vision-pro'));
  return to_jsonb(row_);
end;
$$;

-- ── Arquivar (vendida), consultar o arquivo, recuperar ──────────────────────
create or replace function public.demos_arquivar_viatura(p_chassis text)
returns bigint
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.viaturas;
  s jsonb;
  quem text;
  novo bigint;
begin
  select * into v from public.viaturas where chassis = p_chassis;
  if not found then raise exception 'Viatura não encontrada.' using errcode = 'P0002'; end if;
  if not ((select public.is_app_admin())
          or ((select public.has_access('demos:precos', 'edit')) and public.viaturas_local_ok(v.local))) then
    raise exception 'Sem permissão para arquivar esta viatura.' using errcode = '42501';
  end if;
  s := public.demos_calc_stats(case jsonb_typeof(v.inputs) when 'object' then v.inputs else '{}'::jsonb end, v.stats);
  select coalesce(nullif(u.nome, ''), u.email) into quem
    from public.app_users u where lower(u.email) = lower(auth.jwt() ->> 'email');
  insert into public.viaturas_vendidas (chassis, matricula, modelo, versao, encomenda, estado_entrega, estado_negocio,
        data_matricula, tipologia, local, marca, kms, observacoes, link_fotos, inputs, stats, preco_final,
        data_venda, vendido_por, iva_dedutivel)
    values (v.chassis, v.matricula, v.modelo, v.versao, v.encomenda, v.estado_entrega, v.estado_negocio,
        v.data_matricula::text, v.tipologia, v.local,
        case when v.marca like '[%' then v.marca::jsonb else jsonb_build_array(coalesce(nullif(v.marca, ''), 'BMW')) end,
        v.kms::text, v.observacoes, v.link_fotos,
        case jsonb_typeof(v.inputs) when 'object' then v.inputs else '{}'::jsonb end, s, (s ->> 'pvp_final')::numeric,
        now(), coalesce(quem, auth.jwt() ->> 'email'), v.iva_dedutivel)
    returning id into novo;
  delete from public.viaturas where chassis = p_chassis;
  insert into public.historico (tabela, acao, registo_id, detalhes)
    values ('viaturas', 'VENDIDA', p_chassis,
            jsonb_build_object('vendido_por', auth.jwt() ->> 'email', 'preco_final', (s ->> 'pvp_final')::numeric, 'origem', 'baviera-vision-pro'));
  return novo;
end;
$$;

create or replace function public.demos_vendidas()
returns setof public.viaturas_vendidas
language sql
stable
security definer
set search_path = ''
as $$
  select v.*
  from public.viaturas_vendidas v
  where (select public.is_app_admin())
     or ((select public.has_access('demos:precos', 'edit')) and public.viaturas_local_ok(v.local))
  order by v.data_venda desc nulls last, v.id desc;
$$;

create or replace function public.demos_repor_viatura(p_id bigint)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v public.viaturas_vendidas;
  mar jsonb;
begin
  select * into v from public.viaturas_vendidas where id = p_id;
  if not found then raise exception 'Registo não encontrado.' using errcode = 'P0002'; end if;
  if not ((select public.is_app_admin())
          or ((select public.has_access('demos:precos', 'edit')) and public.viaturas_local_ok(v.local))) then
    raise exception 'Sem permissão para recuperar esta viatura.' using errcode = '42501';
  end if;
  if exists (select 1 from public.viaturas where chassis = v.chassis) then
    raise exception 'Já existe no parque uma viatura com o chassis %.', v.chassis using errcode = '23505';
  end if;
  mar := case jsonb_typeof(v.marca) when 'array' then v.marca else jsonb_build_array('BMW') end;
  insert into public.viaturas (chassis, matricula, modelo, versao, encomenda, estado_entrega, estado_negocio, data_matricula,
        tipologia, local, marca, kms, observacoes, link_fotos, inputs, stats, iva_dedutivel)
    values (v.chassis, v.matricula, v.modelo, v.versao, v.encomenda, v.estado_entrega, v.estado_negocio,
        case when v.data_matricula ~ '^\d{4}-\d{2}-\d{2}' then substr(v.data_matricula, 1, 10)::date end,
        v.tipologia, v.local, mar::text,
        case when v.kms ~ '^\d{1,9}$' then v.kms::int end, v.observacoes, v.link_fotos, v.inputs, v.stats, v.iva_dedutivel);
  delete from public.viaturas_vendidas where id = p_id;
  insert into public.historico (tabela, acao, registo_id, detalhes)
    values ('viaturas', 'REPOR', v.chassis, jsonb_build_object('reposto_por', auth.jwt() ->> 'email', 'origem', 'baviera-vision-pro'));
  return v.chassis;
end;
$$;

